// Replays the committed vectors through the verifying side of the Go code.
func TestVectorsVerify(t *testing.T) {
	raw, err := os.ReadFile(filepath.Clean(vecPath))
	if err != nil {
		t.Skip("no vectors yet")
	}
	var vf vectorFile
	if err := json.Unmarshal(raw, &vf); err != nil {
		t.Fatal(err)
	}
	for _, c := range vf.Merkle {
		ls, _ := merkle.DecodeHex(c.Leaves)
		root, _ := hex.DecodeString(c.Root)
		proof, _ := merkle.DecodeHex(c.Proof)
		var ok bool
		switch c.Kind {
		case "root":
			ok = hex.EncodeToString(merkle.RootRaw(ls)) == c.Root
		case "inclusion":
			ok = merkle.VerifyInclusionRaw(ls[c.Index], uint64(c.Index), uint64(len(ls)), proof, root)
		case "consistency":
			old, _ := hex.DecodeString(c.OldRoot)
			ok = merkle.VerifyConsistency(uint64(c.OldSize), uint64(len(ls)), old, root, proof)
		}
		if ok != c.Valid {
			t.Errorf("merkle %s: got %v want %v", c.Name, ok, c.Valid)
		}
	}
	for _, c := range vf.Requests {
		pub, _ := base64.StdEncoding.DecodeString(c.PublicKey)
		ms, _ := time.Parse(time.RFC3339, "2026-09-21T13:33:20Z")
		_ = ms
		now := time.UnixMilli(1790000000000)
		if ok, why := contract.VerifyRequest(pub, c.Method, c.Path, c.Timestamp, c.Nonce, c.Signature, []byte(c.Body), now); !ok {
			t.Errorf("request %s: %s", c.Name, why)
		}
	}
	for _, c := range vf.Notes {
		n, err := tlog.ParseNote([]byte(c.Signed))
		if err != nil {
			t.Fatal(err)
		}
		name, _, pub, err := tlog.ParseVkey(c.LogVkey)
		if err != nil || tlog.VerifyLog(n, name, pub) != nil {
			t.Errorf("note %s: log signature", c.Name)
		}
		if c.Witness != "" {
			w, _ := tlog.WitnessFromVkey(c.Witness)
			at, ok, err := tlog.VerifyCosig(n, w)
			if err != nil || !ok || at.Unix() != c.CosigTime {
				t.Errorf("note %s: cosignature", c.Name)
			}
		}
	}
}
