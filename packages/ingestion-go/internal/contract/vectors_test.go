func build(t *testing.T, o map[string]string, fixHash bool) string {
	f := base()
	for k, v := range o {
		f[k] = v
	}
	if fixHash {
		if _, set := o["payload_hash"]; !set {
			var p *contract.Value
			if pv, ok := f["payload"]; ok && pv != del {
				v, err := contract.Parse([]byte(pv))
				if err != nil {
					t.Fatalf("bad payload in builder: %v", err)
				}
				if v.Kind != contract.Null {
					p = v
				}
			}
			f["payload_hash"] = `"` + contract.PayloadHash(p) + `"`
		}
	}
	var parts []string
	for _, k := range fieldOrder {
		v, ok := f[k]
		if !ok || v == del {
			continue
		}
		parts = append(parts, `"`+k+`":`+v)
	}
	for k, v := range o { // extra (unknown) fields
		known := false
		for _, fk := range fieldOrder {
			if fk == k {
				known = true
			}
		}
		if !known && v != del {
			parts = append(parts, `"`+k+`":`+v)
		}
	}
	return "{" + strings.Join(parts, ",") + "}"
}

func nest(depth int) string {
	return strings.Repeat(`{"a":`, depth) + "1" + strings.Repeat("}", depth)
}

